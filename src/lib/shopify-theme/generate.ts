/** Liquid/JSON is generated as data, so anything from the source page is escaped. */
function esc(value: string): string {
  return (value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function json(value: unknown): string {
  return JSON.stringify(value, null, 2);
}

