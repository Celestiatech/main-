export async function zipTheme(files: ThemeFile[]): Promise<Buffer> {
  const zip = new JSZip();
  for (const file of files) {
    zip.file(file.path, file.contents);
  }
  return zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
}
