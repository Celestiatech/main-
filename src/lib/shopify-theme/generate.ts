function themeJs(): string {
  return `// Minimal theme behaviour. Shopify handles cart and checkout itself.
document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('details').forEach((item) => {
    item.addEventListener('toggle', () => {
      if (!item.open) return;
      item.parentElement?.querySelectorAll('details[open]').forEach((other) => {
        if (other !== item) other.open = false;
      });
    });
  });
});
`;
}

const HOME_ORDER = ["hero", "image-with-text", "featured-collection", "testimonials", "faq"];

export function buildThemeFiles(
  site: ExtractedSite,
  authorizedBy: string,
  assets: AssetMap = {}
): ThemeFile[] {
  const indexTemplate = {
    sections: Object.fromEntries(HOME_ORDER.map((type) => [type, { type, settings: {} }])),
    order: HOME_ORDER,
  };

  return [
    { path: "layout/theme.liquid", contents: layout(site) },

    { path: "sections/header.liquid", contents: headerSection(site, assets) },
    { path: "sections/hero.liquid", contents: heroSection(site, assets) },
    { path: "sections/image-with-text.liquid", contents: imageWithTextSection(site, assets) },
    { path: "sections/featured-collection.liquid", contents: featuredCollectionSection(site, assets) },
    { path: "sections/testimonials.liquid", contents: testimonialsSection(site) },
    { path: "sections/faq.liquid", contents: faqSection(site) },
    { path: "sections/footer.liquid", contents: footerSection(site) },
    { path: "sections/main-product.liquid", contents: mainProductSection() },
    { path: "sections/main-collection.liquid", contents: mainCollectionSection() },
    { path: "sections/main-page.liquid", contents: mainPageSection() },

    { path: "snippets/card-product.liquid", contents: cardProductSnippet() },

    { path: "templates/index.json", contents: json(indexTemplate) },
    {
      path: "templates/product.json",
      contents: json({ sections: { main: { type: "main-product" } }, order: ["main"] }),
    },
    {
      path: "templates/collection.json",
      contents: json({ sections: { main: { type: "main-collection" } }, order: ["main"] }),
    },
    {
      path: "templates/page.json",
      contents: json({ sections: { main: { type: "main-page" } }, order: ["main"] }),
    },

    { path: "config/settings_schema.json", contents: settingsSchema(site) },
    {
      path: "config/settings_data.json",
      contents: json({ current: { accent_color: site.colors.accent, text_color: site.colors.text } }),
    },

    { path: "assets/theme.css", contents: themeCss(site) },
    { path: "assets/theme.js", contents: themeJs() },
    {
      path: "assets/conversion-manifest.json",
      contents: json({
        generator: "W3Tech Shopify Theme Generator",
        sourceUrl: site.sourceUrl,
        convertedAt: site.extractedAt,
        authorizedBy,
        importedAssets: assets,
        detected: {
          hero: Boolean(site.hero),
          imageWithText: Boolean(site.imageWithText),
          featuredCards: site.featured?.cards.length ?? 0,
          testimonials: site.testimonials?.items.length ?? 0,
          faq: site.faq?.items.length ?? 0,
          headerLinks: site.header.links.length,
          footerLinks: site.footer.links.length,
        },
        warnings: site.warnings,
      }),
    },
  ];
}

